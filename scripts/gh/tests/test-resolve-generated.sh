# ---------------------------------------------------------------------------
# MUTANTS
#
# Each mutation removes exactly one control from a copy of the tool and re-runs
# the case that control is there for. The case must go RED. A mutation whose
# `sed` matches nothing would prove the opposite of what it looks like it
# proves, so every mutation is checked for having actually changed the file
# before it is run.
# ---------------------------------------------------------------------------
echo
echo "== mutants: knocking out one control at a time"
mut_run=0; mut_caught=0

mutate() {  # <sed expression> -> path of the mutated tool, or empty
  local expr="$1" out="$LAB/mutant.sh"
  sed "$expr" "$TOOL" > "$out" 2>/dev/null
  if cmp -s "$TOOL" "$out"; then return 1; fi
  printf '%s\n' "$out"
}

mres() {  # <label> <caught: yes|no> [detail]
  mut_run=$((mut_run+1))
  if [ "$2" = yes ]; then
    printf '  CAUGHT    %-54s %s\n' "$1" "${3:-}"; mut_caught=$((mut_caught+1))
  else
    printf '  SURVIVED  %-54s %s\n' "$1" "${3:-}"
    printf '            the battery does NOT notice this. Its green says less than it looks.\n'
    fail=$((fail+1))
  fi
}

# m1: keep "ours" and never run the emitter. Case (a) must stop being rc 0.
if M="$(mutate 's/^RUN_EMITTER=1$/RUN_EMITTER=0/')"; then
  d="$LAB/m1"; build_repo "$d"; doc_conflict_inside "$d"
  rc="$(run_tool "$d" "$M" docs/census.md)"
  ok=0; [ "$rc" = 0 ] && grep -q '^- files counted: 3$' "$d/docs/census.md" && ok=1
  mres "m1 never runs the emitter (case a)" "$([ "$ok" -eq 0 ] && echo yes || echo no)" "rc=$rc"
else
  mres "m1 never runs the emitter (case a)" no "the sed matched nothing"
fi

# m2: write even when a hunk is not generated. Case (c) must stop being rc 1
#     with an untouched tree.
if M="$(mutate 's/^GUARD_NON_GENERATED=1$/GUARD_NON_GENERATED=0/')"; then
  d="$LAB/m2"; build_repo "$d"
  { printf '# mixed\n\n'
    marker_begin census scripts/gates/lib/fake_census.py
    printf -- '- files counted: 2\n'
    printf '<<<<<<< HEAD\n- files: a.txt, one.txt\n=======\n- files: b.txt, one.txt\n>>>>>>> feat/b\n'
    marker_end census
    printf '\n<<<<<<< HEAD\nProse one branch wrote.\n=======\nProse the other wrote.\n>>>>>>> feat/b\n'
  } > "$d/docs/census.md"
