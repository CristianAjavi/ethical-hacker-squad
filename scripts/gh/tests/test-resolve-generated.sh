res "b. and it names the lines" "$(grep -c 'lines 8-12' "$LAB/out.txt")" 1
res "b. and the tree is byte-identical" "$(treesum "$d")" "$before"

# ---------------------------------------------------------------------------
# c. FAIL CLOSED: one hunk in, one hunk out -> nothing at all is written
# ---------------------------------------------------------------------------
d="$LAB/c"; build_repo "$d"
{ printf '# Census of a throwaway repository\n\n'
  marker_begin census scripts/gates/lib/fake_census.py
  printf -- '- files counted: 2\n'
  printf '<<<<<<< HEAD\n- files: a.txt, one.txt\n=======\n- files: b.txt, one.txt\n>>>>>>> feat/b\n'
  marker_end census
  printf '\n<<<<<<< HEAD\nProse one branch wrote.\n=======\nProse the other wrote.\n>>>>>>> feat/b\n'
} > "$d/docs/census.md"
before="$(treesum "$d")"
res "c. one hunk in, one hunk out -> rc 1" "$(run_tool "$d" "$TOOL" docs/census.md)" 1 "NOTHING has been written"
res "c. the generated hunk was NOT resolved either" "$(treesum "$d")" "$before"
