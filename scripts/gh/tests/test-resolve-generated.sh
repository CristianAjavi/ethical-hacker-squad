# ---------------------------------------------------------------------------
# d. the marker names an emitter that is not in the tree
# ---------------------------------------------------------------------------
d="$LAB/d"; build_repo "$d"
doc_conflict_inside "$d" scripts/gates/lib/ghost_census.py
before="$(treesum "$d")"
res "d. marker names an emitter nobody tracks -> rc 2" "$(run_tool "$d" "$TOOL" docs/census.md)" 2 "git does not track it"
res "d. and nothing was written" "$(treesum "$d")" "$before"

# d2. the same, mixed with a region whose emitter IS fine. One bad emitter must
#     stop the WHOLE run, or the good half lands and the bad half silently keeps
