rm -f "$d/.emitter-ran"
unmerged="$(G "$d" diff --name-only --diff-filter=U | tr '\n' ' ')"
res "the fixture really is an unmerged tree" "$unmerged" "docs/census.md "
res "a. conflict inside the block, no PATH given -> rc 0" "$(run_tool "$d" "$TOOL")" 0 "regenerated"
res "a. and it says both sides were stale" "$(grep -c 'BOTH sides were stale' "$LAB/out.txt")" 1
res "a. no conflict marker survives" \
    "$(grep -c -e '^<<<<<<< ' -e '^=======$' -e '^>>>>>>> ' "$d/docs/census.md")" 0
res "a. the block says what the tree says, not what a branch said" \
    "$(grep -c '^- files counted: 3$' "$d/docs/census.md")" 1
res "a. and the emitter's own check mode agrees" \
    "$( cd "$d" && python3 -- scripts/gates/lib/fake_census.py >/dev/null 2>&1; echo $? )" 0

