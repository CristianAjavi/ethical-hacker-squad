#!/usr/bin/env bash
# Tests scripts/gh/resolve-generated.sh on throwaway repositories built here.
#
# The tool exists because a conflict inside a GENERATED block is not a decision:
# both sides are stale copies of something a program emits, and the merged tree
# has a third answer that neither branch ever saw. Case `inside-the-block` is
# that situation in miniature - two branches each add a file and each rewrites
# the census block to say "2", and the merged tree has three.
#
# Everything here is hermetic: `git init` under a mktemp directory, emitters
# written INSIDE the throwaway repository (never in this one), no network, and
# a trap that removes the lot. The emitters drop a sentinel file the moment they
# start, which is how the security cases prove that a refused path was not
# merely reported - it was not executed.
#
# The last section MUTATES the tool and re-runs the case each mutation should
# break. A battery that has never been shown to go red is a battery whose green
# says nothing.
#
# Exit codes: 0 = every case behaved | 1 = some case did not | 2 = harness broke.
set -uo pipefail

SP="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SP/../../.." && pwd)"
TOOL_REL="scripts/gh/resolve-generated.sh"
TOOL="$ROOT/$TOOL_REL"
[ -f "$TOOL" ] || { echo "  COULD NOT MEASURE: $TOOL_REL is missing (rc 2)"; exit 2; }
command -v git     >/dev/null 2>&1 || { echo "  COULD NOT MEASURE: git is missing (rc 2)"; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "  COULD NOT MEASURE: python3 is missing (rc 2)"; exit 2; }

# Hermetic git: whatever this machine has in ~/.gitconfig must not decide what
# a conflict looks like. `rerere` in particular would resolve the headline case
# from a cache and leave the battery measuring nothing.
export GIT_CONFIG_NOSYSTEM=1
export GIT_CONFIG_GLOBAL=/dev/null

LAB="$(mktemp -d)"; trap 'rm -rf "$LAB"' EXIT
pass=0; fail=0

G() { git -C "$1" -c user.email=t@e -c user.name=t -c rerere.enabled=false \
               -c merge.conflictstyle=merge -c core.autocrlf=false "${@:2}"; }

run_tool() {  # <repo> <tool> [args...] -> prints rc, output lands in $LAB/out.txt
  local d="$1" t="$2"; shift 2
  ( cd "$d" && bash "$t" "$@" >"$LAB/out.txt" 2>&1 ); echo $?
}

res() {  # <label> <got> <want> [needle]
  local label="$1" got="$2" want="$3" needle="${4:-}"
  if [ "$got" = "$want" ] && { [ -z "$needle" ] || grep -qi -- "$needle" "$LAB/out.txt"; }; then
    printf '  PASS  %-56s rc=%s\n' "$label" "$got"; pass=$((pass+1))
  else
    printf '  FAIL  %-56s rc=%s (expected %s)\n' "$label" "$got" "$want"
    sed 's/^/        | /' "$LAB/out.txt" | tail -12; fail=$((fail+1))
  fi
}

# One number for the whole tree, .git excluded. "Nothing was written" is a claim
# about the TREE, not about the one file the case happens to look at, and a
# resolver that fails closed on one file while quietly rewriting another would
# pass a narrower check.
treesum() { ( cd "$1" && find . -path ./.git -prune -o -type f -print | LC_ALL=C sort | xargs cksum | cksum ); }

# ---------------------------------------------------------------------------
# Fixtures: a throwaway repository with a real generated block and real emitters
# ---------------------------------------------------------------------------

# A tiny stand-in for scripts/gates/lib/doc_census.py. It counts the .txt files
# under data/ and rewrites every region whose begin marker names IT - which is
# the property the tool relies on and the reason the tool reads the emitter out
# of the file instead of keeping a list.
emitter() {  # <repo> <repo-relative path> <normal|lazy|flaky|angry>
  local d="$1" rel="$2" mode="$3"
  mkdir -p "$d/$(dirname "$rel")"
  { printf 'SELF = "%s"\nMODE = "%s"\n' "$rel" "$mode"
    cat <<'PY'
import pathlib, re, sys

# The sentinel is written before anything else: it is how the battery proves an
# emitter the tool refused was not merely reported but genuinely never ran.
with open(".emitter-ran", "a") as fh:
    fh.write(SELF + " " + " ".join(sys.argv[1:]) + "\n")

if MODE == "angry":
    sys.stderr.write("this emitter refuses to run\n")
    raise SystemExit(3)

DOC = pathlib.Path("docs/census.md")
WRITE = "--write" in sys.argv[1:]
BEGIN = re.compile(r"<!--\s*([A-Za-z0-9_.-]+):begin \(generated by (\S+)")
END = re.compile(r"<!--\s*([A-Za-z0-9_.-]+):end\s*-->")


def block(tag):
    d = pathlib.Path("data")
    names = sorted(p.name for p in d.glob("*.txt")) if d.is_dir() else []
    return ["<!-- %s:begin (generated by %s - do not edit by hand) -->" % (tag, SELF),
            "- files counted: %d" % len(names),
            "- files: %s" % ", ".join(names),
            "<!-- %s:end -->" % tag]


if not DOC.exists():
    sys.stderr.write("there is no %s to emit into\n" % DOC)
    raise SystemExit(2)

lines = DOC.read_text().split("\n")
out, i, mismatch = [], 0, False
while i < len(lines):
    mb = BEGIN.search(lines[i])
    if mb and mb.group(2) == SELF:
        tag = mb.group(1)
        j = i + 1
        while j < len(lines) and not (END.search(lines[j]) and END.search(lines[j]).group(1) == tag):
            j += 1
        if j >= len(lines):
            sys.stderr.write("the %s block is never closed\n" % tag)
            raise SystemExit(2)
        cur, new = lines[i:j + 1], block(tag)
        if cur != new:
            mismatch = True
        out.extend(cur if MODE == "lazy" else new)
        i = j + 1
        continue
    out.append(lines[i])
    i += 1

if WRITE:
    DOC.write_text("\n".join(out))
    raise SystemExit(0)
if MODE == "lazy":
    raise SystemExit(0)
if MODE == "flaky":
    raise SystemExit(1)
raise SystemExit(1 if mismatch else 0)
PY
  } > "$d/$rel"
}

marker_begin() { printf '<!-- %s:begin (generated by %s - do not edit by hand) -->\n' "$1" "$2"; }
marker_end()   { printf '<!-- %s:end -->\n' "$1"; }

# The tree every hand-built case starts from: three files under data/, so a
# block that claims two is stale and a regeneration really moves it.
build_repo() {  # <dir> [<emitter-path>:<mode> ...]
  local d="$1" spec
  mkdir -p "$d/docs" "$d/data" "$d/tools"
  printf 'one\n' > "$d/data/one.txt"
  printf 'a\n'   > "$d/data/a.txt"
  printf 'b\n'   > "$d/data/b.txt"
  emitter "$d" scripts/gates/lib/fake_census.py normal
  for spec in "${@:2}"; do emitter "$d" "${spec%%:*}" "${spec#*:}"; done
  { printf '# Census of a throwaway repository\n\n'
    printf 'Prose above the block, which nobody generates.\n\n'
    marker_begin census scripts/gates/lib/fake_census.py
    printf -- '- files counted: 3\n- files: a.txt, b.txt, one.txt\n'
    marker_end census
    printf '\nProse below the block, also nobody edits it by hand.\n'
  } > "$d/docs/census.md"
  git -C "$d" init -q -b main
  G "$d" add -A; G "$d" commit -qm base
}

# A conflict BETWEEN the markers: both sides stale, the tree says three.
doc_conflict_inside() {  # <dir> [emitter-path-for-the-marker]
  local d="$1" em="${2:-scripts/gates/lib/fake_census.py}"
  { printf '# Census of a throwaway repository\n\n'
    printf 'Prose above the block, which nobody generates.\n\n'
    marker_begin census "$em"
    printf -- '- files counted: 2\n'
    printf '<<<<<<< HEAD\n- files: a.txt, one.txt\n=======\n- files: b.txt, one.txt\n>>>>>>> feat/b\n'
    marker_end census
    printf '\nProse below the block, also nobody edits it by hand.\n'
  } > "$d/docs/census.md"
}

