G "$d" checkout -q -b feat/a
printf 'a\n' > "$d/data/a.txt"
( cd "$d" && python3 -- scripts/gates/lib/fake_census.py --write )
G "$d" add -A; G "$d" commit -qm "branch a adds a.txt"
G "$d" checkout -q main; G "$d" checkout -q -b feat/b
printf 'b\n' > "$d/data/b.txt"
( cd "$d" && python3 -- scripts/gates/lib/fake_census.py --write )
